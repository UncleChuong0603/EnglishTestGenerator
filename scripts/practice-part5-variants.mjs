export function varyPart5Sentence(sentence, patternIndex, variantIndex) {
  const [needle, alternatives] = variants[patternIndex] ?? [];
  if (!needle || !sentence.includes(needle)) throw new Error(`Part 5 variation ${patternIndex} does not match its sentence: ${sentence}`);
  return sentence.replace(needle, alternatives[variantIndex % alternatives.length]);
}
