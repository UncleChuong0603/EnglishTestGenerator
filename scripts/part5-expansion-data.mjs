const skillFor = (subSkill) => ["business_vocabulary", "contextual_vocabulary", "collocations", "phrasal_expressions"].includes(subSkill) ? "vocabulary" : "grammar";

function make(subSkill, rows) {
  return rows.map(([text, correct, ...distractors], index) => {
    const answerIndex = index % 4;
    const choices = [...distractors];
    choices.splice(answerIndex, 0, correct);
    return {
      key: `p5x-${subSkill}-${String(index + 1).padStart(2, "0")}`,
      toeicPart: 5,
      questionType: "incomplete_sentence",
      skill: skillFor(subSkill),
      subSkill,
      difficulty: index < 2 ? "easy" : index < 6 ? "medium" : "hard",
      status: "published",
      text,
      options: choices.map((choice, optionIndex) => ({ key: KEYS[optionIndex], text: choice })),
      answer: KEYS[answerIndex],
      explanationEn: `${reasons[subSkill][0]} “${correct}” is correct.`,
      explanationVi: `${reasons[subSkill][1]} “${correct}” là đáp án đúng.`,
    };
  });
}

